/** Достаёт текст ответа из разных форматов (Responses API и chat completions) */
function extractText(data) {
  if (typeof data?.output_text === 'string' && data.output_text.trim()) return data.output_text;

  if (Array.isArray(data?.output)) {
    const parts = [];
    for (const item of data.output) {
      if (Array.isArray(item?.content)) {
        for (const c of item.content) {
          if (typeof c?.text === 'string') parts.push(c.text);
        }
      }
    }
    if (parts.length) return parts.join('\n');
  }

  return data?.choices?.[0]?.message?.content ?? '';
}

/**
 * KIE отвечает потоком SSE (Content-Type: text/event-stream) даже когда
 * stream не запрошен. Строки вида: data: {"type":"response.output_text.delta",...}
 *
 * Собираем текст двумя способами и берём тот, что получился:
 *   1. из финального события response.completed — там лежит готовый объект;
 *   2. склейкой всех response.output_text.delta.
 */
function parseSse(raw) {
  const events = [];
  for (const line of String(raw).split('\n')) {
    const t = line.trim();
    if (!t.startsWith('data:')) continue;
    const payload = t.slice(5).trim();
    if (!payload || payload === '[DONE]') continue;
    try {
      events.push(JSON.parse(payload));
    } catch { /* неполная или служебная строка — пропускаем */ }
  }

  if (!events.length) return { text: '', error: null };

  let text = '';
  for (const ev of events) {
    if (ev?.type === 'response.output_text.delta' && typeof ev.delta === 'string') {
      text += ev.delta;
    }
  }

  const completed = events.find((e) => e?.type === 'response.completed' && e?.response);
  if (completed) {
    const err = completed.response?.error;
    if (err) return { text: '', error: err?.message || 'request failed' };
    const fromFinal = extractText(completed.response);
    if (fromFinal) return { text: fromFinal, error: null };
  }

  // Явная ошибка внутри потока
  const failed = events.find((e) => e?.type === 'response.failed' || e?.error);
  if (failed && !text) {
    return { text: '', error: failed?.response?.error?.message || failed?.error?.message || 'stream failed' };
  }

  return { text, error: null };
}

/** Вырезает JSON-объект из ответа модели, даже если есть markdown-обёртка */
function parseJsonLoose(raw) {
  let s = String(raw || '').trim();
  s = s.replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '').trim();
  try {
    return JSON.parse(s);
  } catch { /* пробуем вырезать объект ниже */ }

  const start = s.indexOf('{');
  const end = s.lastIndexOf('}');
  if (start !== -1 && end > start) {
    try {
      return JSON.parse(s.slice(start, end + 1));
    } catch { /* не вышло */ }
  }
  return null;
}

/** Одна попытка запроса. mode: 'responses' | 'chat' */
async function tryProvider(provider, mode, prompt, signal, maxTokens = 6500) {
  const isResponses = mode === 'responses';
  const url = isResponses ? `${provider.base}/responses` : `${provider.base}/chat/completions`;

  const body = isResponses
    ? { model: provider.model, input: prompt, max_output_tokens: maxTokens }
    : { model: provider.model, messages: [{ role: 'user', content: prompt }],
        temperature: 0.5, max_tokens: maxTokens };

  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      Authorization: `Bearer ${provider.key}`,
    },
    body: JSON.stringify(body),
    signal,
  });

  if (!res.ok) {
    const text = (await res.text()).slice(0, 300);
    console.warn(`[llm] ${provider.name}/${mode} → HTTP ${res.status}: ${text}`);
    return null;
  }

  const contentType = res.headers.get('content-type') || '';
  const rawBody = await res.text();

  // KIE отдаёт SSE независимо от запрошенного stream
  let text = '';
  if (contentType.includes('text/event-stream') || rawBody.trimStart().startsWith('event:')
      || rawBody.trimStart().startsWith('data:')) {
    const { text: sseText, error } = parseSse(rawBody);
    if (error) {
      console.warn(`[llm] ${provider.name}/${mode} → ошибка в потоке: ${error}`);
      return null;
    }
    text = sseText;
  } else {
    let data;
    try {
      data = JSON.parse(rawBody);
    } catch {
      console.warn(`[llm] ${provider.name}/${mode} → не удалось разобрать ответ `
        + `(${contentType}). Первые 200 символов: ${rawBody.slice(0, 200)}`);
      return null;
    }
    // Ошибки вида {"code":422,"msg":"..."} приходят с HTTP 200
    if (data && typeof data.code === 'number' && data.code >= 400) {
      console.warn(`[llm] ${provider.name}/${mode} → code ${data.code}: ${data.msg}`);
      return null;
    }
    text = extractText(data);
  }

  const parsed = parseJsonLoose(text);
  if (!parsed) {
    console.warn(`[llm] ${provider.name}/${mode} → текст не разобрался как JSON. `
      + `Первые 200 символов: ${String(text).slice(0, 200)}`);
    return null;
  }

  console.log(`[llm] ок: провайдер ${provider.name}, режим ${mode}, модель ${provider.model}`);
  return { parsed, provider: provider.name, mode };
}

