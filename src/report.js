/**
 * Собирает полный разбор карты.
 * @param {object} chart результат calculateChart()
 * @param {{ useLlm?: boolean }} [opts]
 */
export async function buildReport(chart, opts = {}) {
  const { sections, aspects } = buildSections(chart);

  let finalSections = sections;
  let source = 'template';
  let forecastSource = 'template';
  let llmInfo = null;

  if (opts.useLlm !== false) {
    const result = await generateWithLlm(chart);
    if (result) {
      finalSections = applyLlm(sections, result.parsed);
      source = 'llm';
      forecastSource = Array.isArray(result.parsed.months) && result.parsed.months.length === 12
        && result.parsed.months.every((month) => typeof month === 'string' && month.trim().length >= 80)
        ? 'llm' : 'template';
      llmInfo = { provider: result.provider, mode: result.mode };
    }
  }

  const sun = chart.bodies.find((b) => b.name === 'Солнце');
  const moon = chart.bodies.find((b) => b.name === 'Луна');
  const asc = chart.ascendant;

  return {
    title: chart.input.name ? `Разбор · ${chart.input.name}` : 'Ваш разбор',
    source,
    forecastSource,
    llm: llmInfo,
    bigThree: {
      sun: { sign: sun.sign, signIndex: sun.signIndex, degree: `${sun.degreeInSign}° ${String(sun.minuteInSign).padStart(2, '0')}'` },
      moon: { sign: moon.sign, signIndex: moon.signIndex, degree: `${moon.degreeInSign}° ${String(moon.minuteInSign).padStart(2, '0')}'` },
      asc: asc.approximate ? { sign: null, signIndex: null, approximate: true }
        : { sign: asc.sign, signIndex: asc.signIndex, approximate: false },
    },
    sections: finalSections,
    aspectsCount: aspects.length,
  };
}

