const ASPECTS = [
  { name: 'conjunction', angle: 0, orb: 8 },
  { name: 'sextile', angle: 60, orb: 4 },
  { name: 'square', angle: 90, orb: 6 },
  { name: 'trine', angle: 120, orb: 6 },
  { name: 'opposition', angle: 180, orb: 8 },
];

function angleDiff(a, b) {
  const d = Math.abs(((a - b) % 360) + 360) % 360;
  return d > 180 ? 360 - d : d;
}

function findAspects(bodies) {
  const found = [];
  for (let i = 0; i < bodies.length; i++) {
    for (let j = i + 1; j < bodies.length; j++) {
      const diff = angleDiff(bodies[i].longitude, bodies[j].longitude);
      for (const a of ASPECTS) {
        const delta = Math.abs(diff - a.angle);
        if (delta <= a.orb) {
          found.push({
            a: bodies[i].name,
            b: bodies[j].name,
            aspect: a.name,
            label: ASPECT_MEANING[a.name].label,
            orb: Number(delta.toFixed(2)),
          });
          break;
        }
      }
    }
  }
  // Сортируем: сначала точные
  return found.sort((x, y) => x.orb - y.orb);
}

