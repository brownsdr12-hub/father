/** Подсказки: сначала совпадение с начала слова, потом — вхождение */
export function searchCities(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const starts = [];
  const contains = [];

  for (const c of CITIES) {
    const n = c.name.toLowerCase();
    if (n.startsWith(q)) starts.push(c);
    else if (n.includes(q)) contains.push(c);
  }

  return [...starts, ...contains].slice(0, limit).map((c) => ({
    name: c.name,
    country: c.tz >= 0 ? 'RU' : '—',
    lat: c.lat,
    lon: c.lon,
    tz: c.tz,
  }));
}

/** Найти город по точному названию (для ручного ввода) */
export function findCity(name) {
  const q = name.trim().toLowerCase();
  return CITIES.find((c) => c.name.toLowerCase() === q) ?? null;
}
